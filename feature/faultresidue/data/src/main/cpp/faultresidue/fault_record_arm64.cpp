// The one live-probe translation unit. It compiles only on arm64, where the kernel projects
// thread.fault_address and thread.fault_code into the signal frame; every other ABI links the
// unsupported stub instead (fault_record_probe_stub.cpp), because reading the fault record there
// has no kernel exit at all and a guessed layout would fabricate evidence.
//
// Reference map for what the frame guarantees (the ACK revisions these paths were read from are
// pinned in EVIDENCE.md):
//   - arch/arm64/include/uapi/asm/sigcontext.h: esr_context and ESR_MAGIC.
//   - arch/arm64/kernel/signal.c: setup_sigframe projects fault_address unconditionally and
//     writes the ESR record only when fault_code is non-zero.
// The frame projection runs on the thread the signal is delivered to, so the signal must be
// directed at this thread (tgkill), not the process (kill): a process-directed signal can run its
// handler on another thread, which would sample that thread's unrelated record.

#include "faultresidue/fault_record_probe.h"

#include <sched.h>
#include <signal.h>
#include <sys/syscall.h>
#include <unistd.h>
#include <ucontext.h>

#include <atomic>
#include <cerrno>
#include <cstdint>
#include <cstring>

namespace duckdetector::faultresidue {

    namespace {

        // One-shot handoff from the handler to the sampler: a sync signal runs the handler on the
        // same thread before return, so a release/acquire pair is enough. volatile alone would let
        // the result read race the frame write.
        std::atomic<bool> g_handler_ran{false};
        FaultRecordResult g_frame_result;

        // Runs inside the signal context of this thread. Everything it touches is static storage or
        // locals; no malloc, no logging, no syscall: the handler must be async-signal-safe because
        // a sampling point that reentered the allocator would corrupt the heap it is observing.
        void fault_record_handler(int, siginfo_t *, void *uctx) {
            auto *frame = static_cast<ucontext_t *>(uctx);
            // sizeof preserves the real region even though the kernel's visible records fit far
            // inside it; find_esr_context walks with bounds checks regardless.
            g_frame_result = read_fault_record_from_frame(
                    static_cast<uint64_t>(frame->uc_mcontext.fault_address),
                    reinterpret_cast<const unsigned char *>(frame->uc_mcontext.__reserved),
                    sizeof(frame->uc_mcontext.__reserved));
            g_handler_ran.store(true, std::memory_order_release);
        }

        bool wait_for_handler() {
            // A synchronous tgkill delivers SIGWINCH to this thread before the syscall returns,
            // so g_handler_ran is normally already set. The bounded spin is a fallback for
            // scheduling jitter; the counter is sized to stay in the microseconds even with no
            // compiler optimizations (Debug builds keep the loop volatile-ish through the atomic).
            for (int spins = 0; spins < 2000000; ++spins) {
                if (g_handler_ran.load(std::memory_order_acquire)) {
                    return true;
                }
                sched_yield();
            }
            return false;
        }

    }  // namespace

    FaultRecordResult probe_fault_record() {
        struct sigaction installer;
        std::memset(&installer, 0, sizeof(installer));
        installer.sa_sigaction = fault_record_handler;
        installer.sa_flags = SA_SIGINFO | SA_RESTART;
        sigemptyset(&installer.sa_mask);

        struct sigaction previous;
        g_handler_ran.store(false, std::memory_order_relaxed);
        g_frame_result = FaultRecordResult{};

        // SIGWINCH is the non-fault signal of this probe: it is never generated by the kernel
        // fault machinery (__do_user_fault / do_signal fault list), so installing the handler and
        // self-directing one cannot be mistaken for the record being observed, and reading the
        // frame does not consume or alter thread.fault_* (they are re-projected per signal).
        if (sigaction(SIGWINCH, &installer, &previous) != 0) {
            FaultRecordResult failed;
            failed.outcome = FaultRecordOutcome::kSetupFailed;
            failed.note = "sigaction failed (errno=" + std::to_string(errno) + ")";
            return failed;
        }

        FaultRecordResult result;
        // tgkill(pid, tid, sig) delivers to exactly this thread, so the frame that runs the
        // handler belongs to the thread whose inherited record matters (see the header note).
        const long delivered = syscall(SYS_tgkill, getpid(), syscall(SYS_gettid), SIGWINCH);
        if (delivered == 0 && wait_for_handler()) {
            result = g_frame_result;
        } else {
            result.outcome = FaultRecordOutcome::kHandlerSilent;
            if (delivered != 0) {
                result.note = "tgkill failed (errno=" + std::to_string(errno) + ")";
            }
        }

        // Restore whatever SIGWINCH disposition this process had before the sample; leaving our
        // handler installed would run it for any later SIGWINCH the system delivers.
        sigaction(SIGWINCH, &previous, nullptr);
        return result;
    }

}  // namespace duckdetector::faultresidue
